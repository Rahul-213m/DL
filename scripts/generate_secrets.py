#!/usr/bin/env python3
"""Generate cryptographically strong secrets for a deployment.

    python scripts/generate_secrets.py            # print to stdout
    python scripts/generate_secrets.py --env .env # append to a file

Uses ``secrets`` (the OS CSPRNG), never ``random``. Refuses to overwrite an
existing value in a file, so a rotated secret is always an explicit act.
"""

from __future__ import annotations

import argparse
import secrets
import string
import sys
from pathlib import Path

#: Characters excluded from generated values: quotes, backslash, and anything
#: that would need escaping in a .env file or a shell command.
SAFE = string.ascii_letters + string.digits + "-_."


def token(length: int = 48) -> str:
    """Return a URL-safe random token of roughly ``length`` bytes."""
    return secrets.token_urlsafe(length)


def password(length: int = 24) -> str:
    """Return a password containing all four character classes."""
    alphabet = string.ascii_letters + string.digits + SAFE
    while True:
        candidate = "".join(secrets.choice(alphabet) for _ in range(length))
        if (
            any(c.islower() for c in candidate)
            and any(c.isupper() for c in candidate)
            and any(c.isdigit() for c in candidate)
            and any(c in SAFE for c in candidate)
        ):
            return candidate


def build() -> dict[str, str]:
    """Return a fresh secret for every key the service requires."""
    return {
        "API_KEY": token(48),
        "JWT_SECRET": token(48),
        "POSTGRES_PASSWORD": password(32),
    }


def main(argv: list[str] | None = None) -> int:
    """Print or append generated secrets."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env", type=Path, help="append to this .env file instead of stdout")
    parser.add_argument("--force", action="store_true", help="replace existing values (rotation)")
    args = parser.parse_args(argv)

    secrets_map = build()

    if args.env is None:
        print("# Generated by scripts/generate_secrets.py")
        print("# Commit nothing from here into git. Store in a secret manager.")
        for key, value in secrets_map.items():
            print(f"{key}={value}")
        return 0

    path: Path = args.env
    existing: set[str] = set()
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            name, separator, _ = line.partition("=")
            if separator:
                existing.add(name.strip())

    appended: list[str] = []
    for key, value in secrets_map.items():
        if key in existing and not args.force:
            print(
                f"error: {key} already present in {path}; pass --force to rotate it",
                file=sys.stderr,
            )
            continue
        appended.append(f"{key}={value}")

    if appended:
        with path.open("a", encoding="utf-8") as handle:
            handle.write("\n# --- generated secrets (do not commit) ---\n")
            handle.write("\n".join(appended) + "\n")
        path.chmod(0o600)
        print(f"appended {len(appended)} secret(s) to {path} (mode 600)", file=sys.stderr)

    return 1 if len(appended) != len(secrets_map) else 0


if __name__ == "__main__":
    raise SystemExit(main())
